"""Mirror Oxidus's brain into Obsidian so it can be browsed in Graph view.

Writes Markdown notes (YAML frontmatter + [[wiki-links]]) under
"<vault>/Oxidus Brain/Brain". Frontmatter follows obsidian-brain artefact
conventions (type / key / tags) plus ``generated_by: oxidus``.

Safety rules:
* Writes only inside the Brain folder.
* Rewrites a file only if it already carries ``generated_by: oxidus``
  (i.e. this exporter made it). Any other file is left alone and reported.
* Never deletes anything. Generated notes that are no longer produced are
  only reported as "stale".
* Adds a graph colour-group config only if the vault has no
  .obsidian/graph.json yet.

CLI:  python -m src.integrations.obsidian_brain_export [--vault PATH] [--dry-run]
"""
from __future__ import annotations

import argparse
import glob
import io
import json
import re
from collections import Counter, defaultdict
from contextlib import redirect_stdout
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BRAIN_SUBDIR = Path("Oxidus Brain") / "Brain"
MARKER = "generated_by: oxidus"
MANIFEST = Path("data") / "obsidian_brain_manifest.json"
_BAD = re.compile(r'[<>:"/\\|?*#^\[\]]+')

COLOR_GROUPS = [  # (tag query, rgb)
    ("tag:#oxidus/hub", 0xF5C542),
    ("tag:#oxidus/domain", 0xE8590C),
    ("tag:#oxidus/topic", 0xFD7E14),
    ("tag:#oxidus/wiki", 0x339AF0),
    ("tag:#oxidus/scripture", 0x9C36B5),
    ("tag:#oxidus/theme", 0xD6336C),
    ("tag:#oxidus/ethics", 0x2F9E44),
    ("tag:#oxidus/conversation", 0x15AABF),
    ("tag:#oxidus/thought", 0x868E96),
    ("tag:#oxidus/question", 0xFAB005),
    ("tag:#oxidus/source", 0x5C7CFA),
]


def _safe(name: str) -> str:
    name = _BAD.sub("-", str(name)).strip().strip(".")
    return re.sub(r"\s+", " ", name)[:120] or "Untitled"


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def _yaml(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return json.dumps(str(v), ensure_ascii=False)


def _read_json(path: Path, default=None):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception:
        return default


def _title(s: str) -> str:
    return " ".join(w[:1].upper() + w[1:] for w in str(s).replace("_", " ").split())


class Note:
    def __init__(self, name, folder, kind, ntype="living/note"):
        self.name, self.folder, self.kind, self.type = name, folder, kind, ntype
        self.kinds = [kind]
        self.props: dict = {}
        self.tags = {f"oxidus/{kind}"}
        self.intro: list[str] = []
        self.sections: dict[str, list[str]] = {}
        self.links: dict[str, list[str]] = defaultdict(list)  # section -> names

    def link(self, section, target, label=""):
        entry = f"{target}|{label}" if label else target
        if entry not in self.links[section] and target != self.name:
            self.links[section].append(entry)

    def render(self, stamp: str) -> str:
        fm = ["---", f"type: {self.type}", f"key: {_slug(self.name)}",
              f"oxidus_kind: {self.kind}", MARKER, f"exported: {stamp}"]
        for k, v in self.props.items():
            if v not in (None, "", []):
                fm.append(f"{k}: {_yaml(v)}")
        fm.append("tags:")
        fm += [f"  - {t}" for t in sorted(self.tags)]
        fm.append("---")
        out = ["\n".join(fm), "", f"# {self.name}", ""]
        out += self.intro
        if self.intro:
            out.append("")
        for title, lines in self.sections.items():
            out += [f"## {title}", *lines, ""]
        for title, entries in self.links.items():
            if not entries:
                continue
            out.append(f"## {title}")
            for e in entries:
                tgt, _, label = e.partition("|")
                out.append(f"- [[{tgt}]]" + (f" ({label})" if label else ""))
            out.append("")
        out.append("*Generated by Oxidus. Edits here are replaced on the next export; "
                   "write your own notes outside the Brain folder.*")
        return "\n".join(out) + "\n"


class BrainExporter:
    def __init__(self, root=ROOT, vault=None):
        self.root = Path(root)
        if vault is None:
            from src.web.blueprints.obsidian import vault_path
            vault = vault_path()
        self.vault = Path(vault)
        self.brain = self.vault / BRAIN_SUBDIR
        self.kb = self.root / "data" / "knowledge_base"
        self.notes: dict[str, Note] = {}
        self.alias: dict[str, str] = {}  # concept key -> note name

    # ---- registry -------------------------------------------------------
    def node(self, name, folder, kind, ntype="living/note", concept=None):
        """Get or create a note. Same concept key = same note (merges kinds)."""
        ckey = (concept or name).strip().lower()
        if ckey in self.alias:
            n = self.notes[self.alias[ckey]]
            if kind not in n.kinds:
                n.kinds.append(kind)
                n.tags.add(f"oxidus/{kind}")
            return n
        safe = _safe(name)
        base, i = safe, 2
        while safe.lower() in self.notes:
            safe = f"{base} ({_title(kind)})" if i == 2 else f"{base} ({_title(kind)} {i})"
            i += 1
        n = Note(safe, folder, kind, ntype)
        self.notes[safe.lower()] = n
        self.alias[ckey] = safe.lower()
        return n

    def find(self, concept):
        k = self.alias.get(str(concept).strip().lower())
        return self.notes.get(k) if k else None

    # ---- collectors -----------------------------------------------------
    def build(self):
        self.root_hub = self.node("Oxidus Brain Map", "", "hub", "living/documentation")
        self.root_hub.intro = [
            "Everything Oxidus knows, mirrored from OxidusArmoury so you can follow it in "
            "Obsidian. Open **Graph view** (Ctrl+G) and start from this note, or open a "
            "hub below and use *Local graph* to see one area at a time.",
        ]
        self.root_hub.sections["Colour the graph"] = [
            "In Graph view > Groups, add these queries to colour each area:",
            *[f"- `{q}`" for q, _ in COLOR_GROUPS],
        ]
        self._hubs = {}
        for key, title, desc in [
            ("domain", "Domains", "Big areas of knowledge Oxidus organises everything under."),
            ("topic", "Topics", "Topics and how they relate (influences, overlaps, includes...)."),
            ("wiki", "Wiki Library", "Articles Oxidus has read, linked to their domain and to each other."),
            ("scripture", "Scripture", "Every book in Oxidus's scripture shelf, by collection, tradition and theme."),
            ("theme", "Themes", "Moral themes tagged in scripture verses, linked to the books that carry them."),
            ("ethics", "Ethics", "Oxidus's non-negotiable boundaries and the ethics texts it studies."),
            ("conversation", "Conversations", "Notes Oxidus kept from conversations, with open action items."),
            ("thought", "Thought Streams", "Oxidus's internal thoughts, one note per day, linked to its goals."),
            ("question", "Open Questions", "Questions Oxidus is waiting on you to answer."),
            ("source", "Sources", "Where knowledge came from."),
        ]:
            h = self.node(title, "", "hub", "living/documentation")
            h.intro = [desc]
            h.link("Up", self.root_hub.name)
            self.root_hub.link("Areas", h.name)
            self._hubs[key] = h
        self._domains(); self._topics(); self._wiki(); self._ethics()
        self._scripture(); self._conversations(); self._thoughts(); self._questions()
        return self

    def _hub(self, key):
        return self._hubs[key]

    def _source(self, name, desc=""):
        s = self.node(name, "Sources", "source")
        if desc and not s.intro:
            s.intro = [desc]
        s.link("Hub", self._hub("source").name)
        self._hub("source").link("Sources", s.name)
        return s

    def _domain(self, name):
        name = _title(name.replace("domain-", ""))
        d = self.node(name, "Domains", "domain")
        if "Hub" not in d.links:
            d.link("Hub", self._hub("domain").name)
            self._hub("domain").link("Domains", d.name)
        return d

    def _domains(self):
        reg = _read_json(self.kb / "metadata" / "topic_registry.json", {}) or {}
        for t in reg.get("topics", []):
            if t.get("type") == "domain":
                d = self._domain(t.get("name") or t.get("id", ""))
                d.props["status"] = t.get("status", "")
        ddir = self.kb / "domains"
        if ddir.exists():
            for sub in sorted(p for p in ddir.iterdir() if p.is_dir()):
                d = self._domain(sub.name)
                readme = sub / "README.md"
                if readme.exists():
                    lines = [l for l in readme.read_text(encoding="utf-8", errors="replace").splitlines()
                             if l.strip() and not l.startswith("# ")]
                    d.sections["Scope"] = lines[:20]

    def _topic(self, name):
        if self.find(name):
            return self.find(name)
        t = self.node(_title(name), "Topics", "topic", concept=name)
        t.link("Hub", self._hub("topic").name)
        self._hub("topic").link("Topics", t.name)
        return t

    def _topics(self):
        m = _read_json(self.kb / "metadata" / "topic_to_domain.json", {}) or {}
        for row in m.get("mappings", []):
            t = self._topic(row.get("topic", ""))
            d = self._domain(row.get("domain_id", ""))
            t.link("Domain", d.name); d.link("Topics", t.name)
        g = _read_json(self.kb / "metadata" / "graph_edges.json", {}) or {}
        for e in g.get("edges", []):
            a, b = self._topic(e.get("from", "")), self._topic(e.get("to", ""))
            rel = e.get("relation", "related")
            a.link("Related", b.name, rel)
            b.link("Related", a.name, f"{rel} (from)")
            for ev in e.get("evidence", []) or []:
                if ev.get("source_url"):
                    a.sections.setdefault("Evidence", []).append(f"- {rel} {b.name}: {ev['source_url']}")

    def _wiki(self):
        wdir = self.kb / "wiki_corpus"
        arts = []
        for p in sorted(wdir.glob("*.md")) if wdir.exists() else []:
            raw = p.read_text(encoding="utf-8", errors="replace")
            meta, body = {}, raw
            if raw.startswith("---"):
                parts = raw.split("---", 2)
                if len(parts) == 3:
                    body = parts[2]
                    for line in parts[1].splitlines():
                        k, _, v = line.partition(":")
                        if k.strip():
                            meta[k.strip()] = v.strip().strip('"')
            title = meta.get("title") or p.stem.rsplit("_", 1)[0]
            arts.append((title, meta, body))
        wiki_src = self._source("Wikipedia", "Encyclopedia articles crawled into the wiki corpus.") if arts else None
        made = []
        for title, meta, body in arts:
            n = self.node(title, "Library/Wiki", "wiki", concept=f"wiki::{title}")
            n.props.update({"url": meta.get("url", ""), "domain": meta.get("domain", ""),
                            "source": meta.get("source", "")})
            summary = body.strip().split("\n== ", 1)[0].strip()
            n.sections["Summary"] = [summary[:1500] + ("..." if len(summary) > 1500 else "")]
            heads = re.findall(r"^==\s*([^=].*?)\s*==\s*$", body, re.M)
            if heads:
                n.sections["Sections"] = [f"- {h}" for h in heads[:25]]
            if meta.get("domain"):
                d = self._domain(meta["domain"]); n.link("Domain", d.name); d.link("Wiki articles", n.name)
            n.link("Hub", self._hub("wiki").name); self._hub("wiki").link("Articles", n.name)
            n.link("Source", wiki_src.name); wiki_src.link("Articles", n.name)
            t = self.alias.get(title.lower())
            if t and self.notes[t].kind == "topic":
                n.link("Topic", self.notes[t].name); self.notes[t].link("Wiki articles", n.name)
            made.append((n, title, body.lower()))
        pats = {title: re.compile(r"\b" + re.escape(title.lower()) + r"\b") for _, title, _ in made}
        for n, title, low in made:
            hits = [(low.count(title2.lower()), m2) for m2, title2, _ in made
                    if m2 is not n and pats[title2].search(low)]
            for _, m2 in sorted(hits, key=lambda x: -x[0])[:25]:
                n.link("Mentions", m2.name); m2.link("Mentioned by", n.name)

    def _scripture(self):
        bdir = self.kb / "bible"
        files = sorted(glob.glob(str(bdir / "*" / "*.json")))
        coll_names = {"old": "Old Testament", "new": "New Testament",
                      "latter-day saint": "Book of Mormon (Collection)"}
        for f in files:
            d = _read_json(Path(f), {}) or {}
            if "chapters" not in d:
                continue
            book = d.get("book") or Path(f).stem
            n = self.node(book, "Library/Scripture", "scripture", concept=f"book::{book}")
            chapters = d.get("chapters") or {}
            verses = sum(len(c) for c in chapters.values())
            n.props.update({"testament": d.get("testament", ""), "translation": d.get("translation", ""),
                            "chapters": len(chapters), "verses": verses})
            first = (chapters.get("1") or {}).get("1", {}).get("text", "") if chapters else ""
            if first:
                n.intro = [f"> {first} ({book} 1:1)"]
            if d.get("source_edition"):
                n.sections["Edition"] = [d["source_edition"]]
            coll = self.node(coll_names.get(d.get("testament"), _title(d.get("testament") or "Other")),
                             "Library/Scripture", "scripture", "living/documentation")
            if "Hub" not in coll.links:
                coll.link("Hub", self._hub("scripture").name); self._hub("scripture").link("Collections", coll.name)
            n.link("Collection", coll.name); coll.link("Books", n.name)
            for tr in d.get("traditions") or []:
                t = self.node(f"{_title(tr)} canon", "Library/Scripture", "scripture", "living/documentation")
                if "Hub" not in t.links:
                    t.link("Hub", self._hub("scripture").name); self._hub("scripture").link("Canons", t.name)
                n.link("Canons", t.name); t.link("Books", n.name)
            tr_name = d.get("translation") or ""
            if tr_name:
                s = self._source("King James Version" if tr_name == "KJV" else tr_name, d.get("license", ""))
                n.link("Source", s.name); s.link("Books", n.name)
            themes = Counter()
            for c in chapters.values():
                for v in c.values():
                    themes.update(v.get("themes") or [])
            for th, cnt in themes.most_common():
                tn = self._theme(th)
                n.link("Themes", tn.name, f"{cnt} verses"); tn.link("Books", n.name, f"{cnt} verses")
            n.link("Hub", self._hub("scripture").name)

    def _theme(self, th):
        existing = self.find(th) or self.find(th.replace("_", " "))
        if existing and existing.kind == "ethics":
            t = existing
            if "theme" not in t.kinds:
                t.kinds.append("theme"); t.tags.add("oxidus/theme")
        else:
            t = self.node(_title(th), "Themes", "theme", concept=th.replace("_", " "))
        if "Themes hub" not in t.links:
            t.link("Themes hub", self._hub("theme").name); self._hub("theme").link("Themes", t.name)
        return t

    def _ethics(self):
        h = self._hub("ethics")
        bounds = {}
        try:
            from src.core.ethics import OxidusEthics
            with redirect_stdout(io.StringIO()):
                bounds = dict(OxidusEthics().immutable_boundaries)
        except Exception:
            pass
        for key, text in bounds.items():
            n = self.node(_title(key), "Ethics", "ethics", concept=key.replace("_", " "))
            n.props["rule"] = "immutable boundary"
            n.intro = [f"**{text}**"]
            n.link("Hub", h.name); h.link("Immutable boundaries", n.name)
        edir = self.kb / "ethics"
        for f in sorted(edir.glob("*.json")) if edir.exists() else []:
            rows = _read_json(f, [])
            for d in rows if isinstance(rows, list) else [rows]:
                if not isinstance(d, dict) or not d.get("title"):
                    continue
                n = self.node(d["title"], "Ethics", "ethics", concept=f"ethicstext::{d['title']}")
                n.props.update({"author": d.get("author", ""), "url": d.get("source_url", ""),
                                "year": d.get("publication_year", "")})
                n.sections["Text"] = [str(d.get("content", ""))[:2000]]
                for k in ("questions_raised", "insights_gained"):
                    if d.get(k):
                        n.sections[_title(k)] = [f"- {x}" for x in d[k]][:20]
                if d.get("author"):
                    a = self.node(d["author"], "Sources", "source", "living/people")
                    a.link("Works", n.name); n.link("Author", a.name)
                    a.link("Hub", self._hub("source").name); self._hub("source").link("Authors", a.name)
                low = (d.get("content", "") + " " + d.get("title", "")).lower()
                for key in bounds:
                    if key.replace("_", " ") in low:
                        n.link("Supports", _title(key))
                n.link("Hub", h.name); h.link("Texts studied", n.name)

    def _linkable(self):
        if not hasattr(self, "_lk"):
            self._lk = [(re.compile(r"\b" + re.escape(n.name.lower()) + r"\b"), n)
                        for n in self.notes.values()
                        if n.kind in ("wiki", "topic", "domain", "theme") and len(n.name) >= 5]
        return self._lk

    def _conversations(self):
        idx = _read_json(self.kb / "notes" / "notes_index.json", {}) or {}
        h = self._hub("conversation")
        for d in idx.get("notes", []):
            topic = (d.get("topic") or d.get("id") or "note").strip()
            n = self.node(f"Conversation - {topic[:60]}", "Conversations", "conversation",
                          "temporal/captures", concept=f"conv::{d.get('id')}")
            n.props.update({"status": d.get("status", ""), "created": d.get("created_at", ""),
                            "next_review": d.get("next_review_at", "")})
            if d.get("summary"):
                n.sections["Summary"] = [str(d["summary"])[:2000]]
            for k in ("questions", "action_items"):
                if d.get(k):
                    n.sections[_title(k)] = [f"- {x}" for x in d[k]][:20]
            low = (topic + " " + str(d.get("summary", ""))).lower()
            for pat, m in self._linkable():
                if pat.search(low):
                    n.link("About", m.name); m.link("Conversations", n.name)
            n.link("Hub", h.name); h.link("Conversations", n.name)

    def _thoughts(self, days=14):
        h = self._hub("thought")
        by_day: dict[str, list] = defaultdict(list)
        for f in sorted(glob.glob(str(self.root / "data" / "thought_streams" / "*.json"))):
            d = _read_json(Path(f), {}) or {}
            for t in d.get("thoughts", []) or []:
                ts = str(t.get("timestamp") or d.get("timestamp") or "")[:10]
                if ts:
                    by_day[ts].append(t)
        goal_re = re.compile(r"Goal '([\w ]+)'")
        for day in sorted(by_day)[-days:]:
            items = by_day[day]
            n = self.node(f"Thoughts {day}", "Thoughts", "thought", "temporal/thoughts")
            types = Counter(t.get("type", "thought") for t in items)
            n.props.update({"date": day, "thoughts": len(items)})
            n.sections["Types"] = [f"- {k}: {v}" for k, v in types.most_common()]
            uniq = Counter(str(t.get("content", ""))[:200] for t in items)
            n.sections["Most frequent"] = [f"- ({c}x) {txt}" for txt, c in uniq.most_common(15)]
            for t in items:
                for g in goal_re.findall(str(t.get("content", ""))):
                    gn = self.node(f"Goal - {_title(g)}", "Thoughts", "thought", "living/note")
                    if "Hub" not in gn.links:
                        gn.link("Hub", h.name); h.link("Goals", gn.name)
                    n.link("Goals", gn.name); gn.link("Thought days", n.name)
            n.link("Hub", h.name); h.link("Days", n.name)

    def _questions(self, limit=60):
        h = self._hub("question")
        q = _read_json(self.root / "data" / "stores" / "questions" / "queue.json", {}) or {}
        items = [x for x in q.get("questions", []) if isinstance(x, dict)]
        items.sort(key=lambda x: x.get("status") != "open")
        for x in items[:limit]:
            qid = x.get("id") or _slug(str(x.get("question", "")))[:12]
            n = self.node(f"Question - {str(x.get('topic') or x.get('question', ''))[:60]}",
                          "Questions", "question", "temporal/captures", concept=f"q::{qid}")
            n.props.update({"status": x.get("status", ""), "reason": x.get("reason", "")})
            n.intro = [str(x.get("question", ""))]
            if x.get("answer"):
                n.sections["Answer"] = [str(x["answer"])]
            topic = self.find(str(x.get("topic", "")))
            if topic:
                n.link("About", topic.name); topic.link("Questions", n.name)
            n.link("Hub", h.name); h.link("Open" if x.get("status") == "open" else "Answered", n.name)
        if not items:
            h.sections["Status"] = ["No questions queued right now."]

    # ---- writing --------------------------------------------------------
    def _graph_config(self, dry):
        cand = [self.vault / "Oxidus Brain" / ".obsidian", self.vault / ".obsidian"]
        obs = next((c for c in cand if c.is_dir()), None)
        if obs is None:
            return "no .obsidian folder found"
        gj = obs / "graph.json"
        if gj.exists():
            return f"left alone (exists): {gj}"
        if not dry:
            gj.write_text(json.dumps({"colorGroups": [
                {"query": q, "color": {"a": 1, "rgb": rgb}} for q, rgb in COLOR_GROUPS]}, indent=2),
                encoding="utf-8")
        return f"created: {gj}"

    def write(self, dry=False) -> dict:
        stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        stats = Counter()
        written_paths = set()
        brain = self.brain.resolve()
        skipped = []
        for n in self.notes.values():
            target = self.brain / n.folder / f"{n.name}.md"
            if brain not in target.resolve().parents and not dry:
                stats["refused"] += 1
                continue
            text = n.render(stamp)
            written_paths.add(str(target.resolve()).lower())
            stats["links"] += sum(len(v) for v in n.links.values())
            if target.exists():
                head = target.read_text(encoding="utf-8", errors="replace")[:2000]
                if MARKER not in head:
                    stats["skipped_user_file"] += 1; skipped.append(str(target)); continue
                full_old = target.read_text(encoding="utf-8", errors="replace")
                if re.sub(r"^exported: .*$", "", full_old, count=1, flags=re.M) == \
                        re.sub(r"^exported: .*$", "", text, count=1, flags=re.M):
                    stats["unchanged"] += 1; continue
                stats["updated"] += 1
            else:
                stats["created"] += 1
            if not dry:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
        stale = []
        if self.brain.exists():
            for p in self.brain.rglob("*.md"):
                if str(p.resolve()).lower() not in written_paths:
                    try:
                        if MARKER in p.read_text(encoding="utf-8", errors="replace")[:2000]:
                            stale.append(str(p))
                    except OSError:
                        pass
        kinds = Counter(n.kind for n in self.notes.values())
        result = {"ok": True, "dry_run": dry, "brain_folder": str(self.brain), "exported": stamp,
                  "notes": len(self.notes), "links": stats["links"], "by_kind": dict(kinds),
                  "created": stats["created"], "updated": stats["updated"],
                  "unchanged": stats["unchanged"], "skipped_user_files": skipped,
                  "stale_generated_files": stale, "graph_config": self._graph_config(dry)}
        if not dry:
            mp = self.root / MANIFEST
            mp.parent.mkdir(parents=True, exist_ok=True)
            mp.write_text(json.dumps({k: v for k, v in result.items()}, indent=2), encoding="utf-8")
        return result


def export_brain(root=ROOT, vault=None, dry_run=False) -> dict:
    return BrainExporter(root, vault).build().write(dry=dry_run)


def last_export(root=ROOT) -> dict | None:
    return _read_json(Path(root) / MANIFEST, None)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Mirror Oxidus's brain into an Obsidian vault.")
    ap.add_argument("--vault", help="Vault path (default: config/obsidian.json)")
    ap.add_argument("--dry-run", action="store_true", help="Count only, write nothing")
    a = ap.parse_args(argv)
    r = export_brain(vault=a.vault, dry_run=a.dry_run)
    print(json.dumps({k: v for k, v in r.items() if k != "stale_generated_files"}, indent=2))
    print(f"stale generated files (kept, not deleted): {len(r['stale_generated_files'])}")


if __name__ == "__main__":
    main()
